export function languageOf(code: string) {
  return code && code !== "auto" ? code : (navigator.language || "en").slice(0, 2)
}

export let t: Strings = en

export function useStrings(code: string) {
  t = languageOf(code) === "ru" ? ru : en
  document.documentElement.lang = languageOf(code)
}
